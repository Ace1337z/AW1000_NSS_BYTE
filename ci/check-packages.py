#!/usr/bin/env python3
"""Deterministic package checks that need no compilation.

The multi-hour image build ends with package/install, where apk refuses two
things that are fully known from the package metadata alone:

  1. a version that is not apk syntax
         ERROR: info field 'version' has invalid value
  2. two packages owning the same file
         ERROR: <pkg> trying to overwrite <path> owned by <pkg>

Both cost a full build cycle because they surface only after every package has
compiled. This script evaluates exactly those two properties from
openwrt/tmp/.packageinfo (generated by prepare.sh) plus each package's
`Package/<name>/install` block.

Resolution is two-pass: every package is scanned for the directories its
install rules create (`$(INSTALL_DIR)`) and copy into (destination ending in
`/`), and that set decides whether a destination without a trailing slash is a
directory or a file. This is what keeps `$(INSTALL_DATA) x $(1)/usr/share/acl.d`
(hostapd) from being read as a file named `/usr/share/acl.d`.

Exit 0: every selected package has an apk-valid version and no two packages
install the same file (packages whose file list cannot be derived statically
are reported as WARN and left unchecked). Exit 1: at least one FAIL line.
"""

import os
import re
import sys

# apk accepts `<version>` with an optional `-r<digits>` revision and nothing
# else containing a dash. opkg-style `4.66-8` (dash + plain number) is rejected.
REVISION_RE = re.compile(r"^r\d+$")

FIELD_KEYS = {
    "Version", "Depends", "Provides", "Section", "Category", "Type",
    "Repository", "Submenu", "Menu-Depends", "Conflicts", "Source",
    "License", "LicenseFiles", "Maintainer", "URL", "ABI-Version",
    "Default",
}

CMD_RES = [
    # $(CP) src dst / $(INSTALL_CONF) src dst / $(INSTALL_BIN) src dst / $(LN) tgt dst
    re.compile(r"\$\((?:CP|INSTALL_CONF|INSTALL_DATA|INSTALL_BIN|INSTALL_PROG|LN)\)\s+(\S+)\s+(\S+)"),
    # cp [-flags] src dst
    re.compile(r"(?<![\w$])cp\s+(?:-\S+\s+)*(\S+)\s+(\S+)"),
    # install [-flags] src dst
    re.compile(r"(?<![\w$])install\s+(?:-\S+\s+)*(\S+)\s+(\S+)"),
]

INSTALL_DIR_RE = re.compile(r"\$\(INSTALL_DIR\)\s+(.+)")

KNOWN_VARS = {
    "LUCI_LIBRARYDIR": "/usr/lib/lua/luci",
    "UCODE_LIBRARYDIR": "/usr/share/ucode",
    "HTDOCS": "/www",
}

LUCI_GENERIC = object()
# luci.mk maps a po directory to a BCP 47 code: LUCI_LC_ALIAS.zh_Hans=zh-cn
ALIAS_RE = re.compile(r"^LUCI_LC_ALIAS\.(\S+)\s*=\s*(\S+)\s*$", re.M)
_ALIAS_CACHE = {}


def luci_aliases(openwrt):
    """LUCI_LC_ALIAS table from the luci feed (feeds/luci/luci.mk), cached."""
    if openwrt in _ALIAS_CACHE:
        return _ALIAS_CACHE[openwrt]
    aliases = {}
    for rel in ("feeds/luci/luci.mk", "package/feeds/luci/luci.mk"):
        path = os.path.join(openwrt, rel)
        if os.path.isfile(path):
            with open(path, encoding="utf-8", errors="replace") as fh:
                aliases = dict(ALIAS_RE.findall(fh.read()))
            break
    _ALIAS_CACHE[openwrt] = aliases
    return aliases


def norm(path):
    path = "/" + path.lstrip("/")
    path = re.sub(r"/+", "/", path)
    return path.rstrip("/") or "/"


def expand_vars(text, values):
    for name, val in values.items():
        text = text.replace("$(%s)" % name, val).replace("${%s}" % name, val)
    return text


def parse_packageinfo(path):
    entries = []
    pending_mk = None
    cur = None
    with open(path, encoding="utf-8", errors="replace") as fh:
        for raw in fh:
            line = raw.rstrip("\n")
            if line.startswith("Source-Makefile:"):
                pending_mk = line.split(":", 1)[1].strip()
            elif line.startswith("Package:"):
                if cur:
                    entries.append(cur)
                cur = {"name": line.split(":", 1)[1].strip(), "makefile": pending_mk}
            elif cur is not None and ":" in line and not line.startswith((" ", "\t")):
                key, _, val = line.partition(":")
                if key in FIELD_KEYS:
                    cur[key] = val.strip()
    if cur:
        entries.append(cur)
    return entries


def enabled_packages(config_path):
    names = set()
    with open(config_path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            m = re.match(r"^CONFIG_PACKAGE_([A-Za-z0-9_.+-]+)=y$", line.strip())
            if m:
                names.add(m.group(1))
    return names


def walk_files(root):
    """Regular files and symlinks below root, relative to it.

    Directories are deliberately excluded: several packages sharing
    /usr/share or /www is normal, only a shared *file* is a conflict.
    """
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        rel = os.path.relpath(dirpath, root)
        rel = "" if rel == "." else rel
        for name in filenames:
            out.append(os.path.join(rel, name) if rel else name)
        for name in dirnames:
            full = os.path.join(dirpath, name)
            if os.path.islink(full):
                out.append(os.path.join(rel, name) if rel else name)
    return out


def install_body(text, pkgname):
    m = re.search(
        r"^define\s+Package/" + re.escape(pkgname) + r"/install\s*$(.*?)^endef\s*$",
        text, re.M | re.S)
    return m.group(1) if m else None


def luci_generic_paths(pkgdir):
    """Mimic feeds/luci/luci.mk Package/$(1)/install for the common dirs."""
    out = []
    for sub, dest in (("luasrc", "/usr/lib/lua/luci"),
                      ("ucode", "/usr/share/ucode"),
                      ("htdocs", "/www"),
                      ("root", "")):
        d = os.path.join(pkgdir, sub)
        if os.path.isdir(d):
            prefix = dest + "/" if dest else "/"
            out.extend(norm(prefix + rel) for rel in walk_files(d) if rel)
    return out


def luci_i18n_paths(pkgdir, name, aliases):
    """File list of a luci-i18n-* subpackage, from feeds/luci/luci.mk.

    Package/luci-i18n-$(LUCI_BASENAME)-$(1)/install writes exactly one
    uci-defaults file and one .lmo per po/<dir>/*.po. $(1) is the BCP 47 code,
    which for some languages differs from the po directory name (zh_Hans ->
    zh-cn), so the alias table is consulted.
    """
    base = name[len("luci-i18n-"):]
    podir = os.path.join(pkgdir, "po")
    if not os.path.isdir(podir):
        return None
    for lang in sorted(os.listdir(podir)):
        code = aliases.get(lang, lang)
        suffix = "-" + code
        if not base.endswith(suffix):
            continue
        basename = base[:-len(suffix)]
        ldir = os.path.join(podir, lang)
        if not basename or not os.path.isdir(ldir):
            continue
        paths = [norm("/etc/uci-defaults/luci-i18n-%s-%s" % (basename, code))]
        for f in sorted(os.listdir(ldir)):
            if f.endswith(".po"):
                paths.append(norm("/usr/lib/lua/luci/i18n/%s.%s.lmo"
                                  % (os.path.splitext(f)[0], code)))
        return paths
    return None


def load_install(openwrt, entry):
    """Return (pkgdir, body_or_LUCI_GENERIC_or_LUCI_I18N_or_None, reason)."""
    mk = entry.get("makefile")
    if not mk:
        return None, None, "no Source-Makefile"
    path = os.path.join(openwrt, mk)
    if not os.path.isfile(path):
        return None, None, "makefile not found"
    with open(path, encoding="utf-8", errors="replace") as fh:
        text = fh.read()
    values = {}
    m = re.search(r"^PKG_NAME\s*[:?]?=\s*(\S+)", text, re.M)
    if m:
        values["PKG_NAME"] = m.group(1)
    pkgdir = os.path.dirname(path)
    body = install_body(expand_vars(text, values), entry["name"])
    if body is not None:
        # Join Makefile line continuations: destinations are often on the
        # following line and the trailing backslash would be read as the dest.
        return pkgdir, re.sub(r"\\\r?\n", " ", body), None
    if entry["name"].startswith("luci-i18n-"):
        return pkgdir, ("i18n", luci_aliases(openwrt)), None
    # luci.mk sets PKG_NAME from the directory name: `PKG_NAME ?= $(notdir $(CURDIR))`.
    derived = values.get("PKG_NAME") or os.path.basename(pkgdir)
    if "luci.mk" in text and entry["name"] == derived:
        return pkgdir, LUCI_GENERIC, None
    return pkgdir, None, "subpackage built by a shared Makefile template"


def dirs_from_body(body):
    dirs = set()
    for m in INSTALL_DIR_RE.finditer(body):
        for tok in m.group(1).split():
            tok = tok.replace("$(1)", "").replace("${1}", "")
            if "$(" in tok or "${" in tok or "*" in tok:
                continue
            if tok:
                dirs.add(norm(tok))
    for cre in CMD_RES:
        for m in cre.finditer(body):
            dst = m.group(2).replace("$(1)", "").replace("${1}", "")
            if dst.endswith("/") and "$(" not in dst:
                dirs.add(norm(dst))
    return dirs


def resolve_cmd(src, dst, pkgdir, known_dirs):
    """Resolve one install command to concrete installed file paths.

    Returns [] when the outcome is not statically knowable.
    """
    dst = dst.replace("$(1)", "").replace("${1}", "")
    for name, val in KNOWN_VARS.items():
        dst = dst.replace("$(%s)" % name, val).replace("${%s}" % name, val)
    if "$(" in dst or "${" in dst or "*" in dst or "?" in dst:
        return []
    dir_hint = dst.endswith("/")
    dst_n = norm(dst) if dst else "/"

    # PKG_BUILD_DIR/<sub>/... mirrors <pkgdir>/<sub>/... in the source tree.
    m = re.match(r"^\$\(PKG_BUILD_DIR\)/([^/]+)(/.*)?$", src)
    if m and not any(c in m.group(1) for c in "*?["):
        src = os.path.join(pkgdir, m.group(1)) + (m.group(2) or "")
    if src.startswith("$(") or "${" in src:
        return []

    if src.endswith("/*") or src.endswith("/.") or src == "*":
        base = src[:-2] if src.endswith("/*") or src.endswith("/.") else "."
        base = os.path.normpath(os.path.join(pkgdir, base))
        if not os.path.isdir(base):
            return []
        prefix = dst_n.rstrip("/") + "/"
        return [norm(prefix + rel) for rel in walk_files(base) if rel]

    abspath = os.path.normpath(os.path.join(pkgdir, src))
    into_dir = dir_hint or dst_n == "/" or dst_n in known_dirs

    if os.path.isdir(abspath):
        if into_dir:
            prefix = dst_n.rstrip("/") + "/" + os.path.basename(abspath) + "/"
        else:
            prefix = dst_n.rstrip("/") + "/"
        return [norm(prefix + rel) for rel in walk_files(abspath) if rel]

    if os.path.isfile(abspath) or os.path.islink(abspath):
        if into_dir:
            return [norm(dst_n.rstrip("/") + "/" + os.path.basename(abspath))]
        return [dst_n]

    return []


def body_paths(body, pkgdir, known_dirs):
    paths = []
    for line in body.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith(("$(INSTALL_DIR)", "ifneq", "ifeq", "endif", "else")):
            continue
        for cre in CMD_RES:
            for m in cre.finditer(line):
                paths.extend(resolve_cmd(m.group(1), m.group(2), pkgdir, known_dirs))
    return paths


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(
        os.path.dirname(os.path.abspath(__file__)))
    openwrt = os.path.join(root, "openwrt")
    info = os.path.join(openwrt, "tmp", ".packageinfo")
    config = os.path.join(openwrt, ".config")

    for need in (info, config):
        if not os.path.isfile(need):
            print("FAIL: missing %s (run ./prepare.sh first)" % need)
            return 2

    entries = {e["name"]: e for e in parse_packageinfo(info)}
    enabled = enabled_packages(config)
    selected = sorted(n for n in enabled if n in entries)

    problems = []

    # 1. apk version grammar.
    for name in selected:
        ver = entries[name].get("Version", "")
        if not ver:
            problems.append("%s: no Version in packageinfo" % name)
            continue
        # kernel.mk fills these in at build time; the index keeps the template.
        if "<" in ver or ">" in ver:
            continue
        if "-" in ver:
            parts = ver.split("-")
            if not (len(parts) == 2 and REVISION_RE.match(parts[1])):
                problems.append(
                    "%s: version '%s' is invalid for apk (need <ver>-r<N>, "
                    "e.g. 4.66-r8)" % (name, ver))

    # 2. Collect install definitions, then the set of directories they create.
    bodies = {}
    unresolved = []
    for name in selected:
        pkgdir, body, reason = load_install(openwrt, entries[name])
        if body is None:
            unresolved.append("%s (%s)" % (name, reason))
            continue
        bodies[name] = (pkgdir, body)

    known_dirs = set()
    for pkgdir, body in bodies.values():
        if body is LUCI_GENERIC or isinstance(body, tuple):
            continue
        known_dirs |= dirs_from_body(body)

    # 3. File ownership collisions.
    owners = {}
    unresolved_i18n = []
    for name, (pkgdir, body) in bodies.items():
        if body is LUCI_GENERIC:
            paths = luci_generic_paths(pkgdir)
        elif isinstance(body, tuple):
            paths = luci_i18n_paths(pkgdir, name, body[1])
            if paths is None:
                unresolved_i18n.append(name)
                continue
        else:
            paths = body_paths(body, pkgdir, known_dirs)
        for p in set(paths):
            owners.setdefault(p, set()).add(name)

    for path, pkgs in sorted(owners.items()):
        if len(pkgs) > 1:
            problems.append("file collision: %s owned by %s"
                            % (path, ", ".join(sorted(pkgs))))

    if unresolved_i18n:
        problems.append("cannot derive the .lmo list for %s (no po/<lang> "
                        "directory)" % ", ".join(sorted(unresolved_i18n)))

    for p in problems:
        print("FAIL: %s" % p)
    if unresolved:
        # The list is long (kmods, i18n, libraries) and constant, so only the
        # first few names are printed; CHECK_PACKAGES_VERBOSE=1 lists them all.
        if os.environ.get("CHECK_PACKAGES_VERBOSE"):
            print("WARN: file list not statically derivable for %d package(s), "
                  "left unchecked: %s" % (len(unresolved), ", ".join(unresolved)))
        else:
            head = ", ".join(unresolved[:8])
            more = ", ..." if len(unresolved) > 8 else ""
            print("WARN: file list not statically derivable for %d package(s) "
                  "(kmods, libraries, template-built subpackages), left unchecked: "
                  "%s%s" % (len(unresolved), head, more))
    if problems:
        return 1

    print("%d selected packages: apk versions valid, %d unique files, "
          "no ownership collisions" % (len(selected), len(owners)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
